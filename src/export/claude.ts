const PET_EMOJI: Record<PetName, string> = {
  'Orange cat': '🐱', 'Gray cat': '🐱', 'Black cat': '🐈‍⬛', Bunny: '🐰', Frog: '🐸',
  Ghost: '👻', Slime: '💧', Chick: '🐥', Puppy: '🐶', Fawn: '🦌',
}

/** Claude Code's "ANSI colors only" themes draw from these 16 slots, so this is how the colors reach Claude. */
export function claudeScheme(t: ClaudeTheme, name: string) {
  return {
    name,
    background: t.background,
    foreground: t.text,
    cursorColor: t.claude,
    selectionBackground: t.userMessageBg,
    black: t.userMessageBg,
    red: t.error,
    green: t.success,
    yellow: t.warning,
    blue: t.permission,
    purple: t.claude,
    cyan: t.planMode,
    white: t.text,
    brightBlack: t.secondaryText,
    brightRed: t.diffRemovedWord,
    brightGreen: t.diffAddedWord,
    brightYellow: t.warning,
    brightBlue: t.permission,
    brightPurple: t.claude,
    brightCyan: t.planMode,
    brightWhite: t.text,
  }
}

function statuslineJs(t: ClaudeTheme, decor: Decor) {
  const pet = decor.pets[0]
  const icon = pet ? `${PET_EMOJI[pet]} ${pet}` : '✻'
  return `#!/usr/bin/env node
// Claude Code status line generated by Theme Mockup Studio.
// Claude Code pipes session JSON on stdin; we print one colored line.
const path = require('path')
const C = ${JSON.stringify({ accent: t.claude, dim: t.secondaryText, text: t.text, plan: t.planMode, ok: t.success })}
const ICON = ${JSON.stringify(icon)}
const fg = (hex, s) => {
  const n = parseInt(hex.slice(1, 7), 16)
  return '\\x1b[38;2;' + ((n >> 16) & 255) + ';' + ((n >> 8) & 255) + ';' + (n & 255) + 'm' + s + '\\x1b[0m'
}
let input = ''
process.stdin.on('data', (d) => (input += d))
process.stdin.on('end', () => {
  let j = {}
  try { j = JSON.parse(input.replace(/^\\uFEFF/, '').trim()) } catch {}
  const model = (j.model && j.model.display_name) || 'Claude'
  const dir = path.basename((j.workspace && j.workspace.current_dir) || j.cwd || process.cwd())
  const sep = fg(C.dim, ' · ')
  process.stdout.write(fg(C.accent, ICON) + sep + fg(C.text, model) + sep + fg(C.plan, dir))
})
`
}

const MERGE_JS = `// Merges a statusLine entry into ~/.claude/settings.json without touching anything else.
const fs = require('fs')
const [file, script] = process.argv.slice(2)
const command = 'node "' + script.split('\\\\').join('/') + '"'
let s = {}
if (fs.existsSync(file)) {
  const raw = fs.readFileSync(file, 'utf8').replace(/^\\uFEFF/, '')
  s = raw.trim() ? JSON.parse(raw) : {}
}
s.statusLine = { type: 'command', command }
fs.writeFileSync(file, JSON.stringify(s, null, 2) + '\\n')
console.log('Updated ' + file)
`

export async function buildClaudePackage(t: ClaudeTheme, decor: Decor): Promise<PackageResult> {
  const themeName = `Claude ${t.baseTheme}`
  const slug = `claude-${slugify(t.baseTheme)}`
  const profileName = `Claude Code (${t.baseTheme})`
  const ansiTheme = isLight(t.background) ? 'Light mode (ANSI colors only)' : 'Dark mode (ANSI colors only)'
  const { background, assets, greetingPs1 } = await windowsDecor(slug, decor, t.background)

  const files = windowsTerminalFiles({
    slug,
    profileName,
    scheme: claudeScheme(t, themeName),
    profile: {
      commandline: greetingPs1
        ? `cmd.exe /k powershell -NoProfile -ExecutionPolicy Bypass -File "${greetingPs1}" & claude`
        : 'cmd.exe /k claude',
      startingDirectory: '%USERPROFILE%',
      font: { face: t.fontFamily, size: t.fontSize },
      tabTitle: 'Claude Code',
    },
    background,
    backgroundOpacity: decor.strength / 100,
    assets,
    extraInstall: `
# --- Claude Code status line ---
if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  Write-Host 'node not found on PATH - skipping the status line.' -ForegroundColor Yellow
} else {
  $claudeDir = Join-Path $env:USERPROFILE '.claude'
  $tmDir = Join-Path $claudeDir 'theme-mockup'
  New-Item -ItemType Directory -Force $tmDir | Out-Null
  Copy-Item (Join-Path $src 'statusline.js') (Join-Path $tmDir 'statusline.js') -Force
  $settings = Join-Path $claudeDir 'settings.json'
  if (Test-Path $settings) { Copy-Item $settings (Join-Path $backupDir 'claude-settings.json') }
  # Pass the bare path: PowerShell 5.1 strips embedded quotes from native-command args, so the JS adds them.
  node (Join-Path $src 'merge-settings.js') $settings (Join-Path $tmDir 'statusline.js')
  Write-Host 'Installed Claude Code status line.' -ForegroundColor Green
}
Write-Host ''
Write-Host 'LAST STEP: in Claude Code run /theme and choose "${ansiTheme}"' -ForegroundColor Magenta
Write-Host 'so Claude uses this profile''s colors.' -ForegroundColor Magenta`,
    extraUninstall: `
Write-Host 'The status line is still set in %USERPROFILE%\\.claude\\settings.json - restore claude-settings.json from your theme-mockup-backups folder to undo it.' -ForegroundColor Yellow`,
    readmeExtra: `
Claude Code
-----------
Claude Code doesn't load custom color themes, but its "ANSI colors only" themes use the
terminal's 16 colors. This package maps your colors onto those slots:
  red=error  green=success  yellow=warning  blue=permission  magenta=Claude accent
  cyan=plan mode  bright black=dim text  bright red/green=diff words

LAST STEP: open the "${profileName}" profile, run /theme and choose "${ansiTheme}".

It also installs a colored status line (~/.claude/theme-mockup/statusline.js) and adds
"statusLine" to ~/.claude/settings.json (the old file is backed up first).
`,
  })
  files['statusline.js'] = statuslineJs(t, decor)
  files['merge-settings.js'] = MERGE_JS

  return {
    filename: `${slug}-claude-code.zip`,
    blob: zip(files),
    note: `Unzip, run install.ps1, restart Windows Terminal, open "${profileName}", then /theme → ${ansiTheme}.`,
  }
}
