const PUBLISHER = 'theme-mockup-studio'

const TOKEN_SCOPES: Record<TokenKey, string[]> = {
  keyword: ['keyword', 'keyword.control', 'storage', 'storage.type', 'storage.modifier'],
  string: ['string', 'string.template', 'punctuation.definition.string'],
  function: ['entity.name.function', 'support.function', 'meta.function-call.generic'],
  variable: ['variable', 'variable.other', 'variable.parameter', 'meta.object-literal.key', 'support.variable.property'],
  type: ['entity.name.type', 'entity.name.class', 'support.type', 'support.class', 'entity.other.inherited-class'],
  number: ['constant.numeric', 'constant.language', 'constant.character'],
  comment: ['comment', 'punctuation.definition.comment'],
  punctuation: ['punctuation', 'meta.brace', 'keyword.operator'],
}

export function vscodeColorTheme(t: VSCodeTheme, name: string) {
  const colors: Record<string, string> = {}
  for (const [k, v] of Object.entries(WORKBENCH_KEYS)) colors[v.key] = t[k as WorkbenchKey]
  Object.assign(colors, {
    focusBorder: t.tabBorder,
    foreground: t.sidebarFg,
    'titleBar.activeForeground': t.sidebarFg,
    'titleBar.inactiveBackground': t.titleBarBg,
    'activityBar.activeBorder': t.activityBarFg,
    'activityBarBadge.background': t.tabBorder,
    'sideBarSectionHeader.background': t.sidebarBg,
    'editorGroupHeader.tabsBackground': t.tabInactiveBg,
    'tab.activeForeground': t.editorFg,
    'tab.border': t.tabInactiveBg,
    'list.activeSelectionBackground': t.listSelection,
    'input.background': shift(t.sidebarBg, 10),
    'dropdown.background': shift(t.sidebarBg, 10),
    'editorWidget.background': t.sidebarBg,
    'terminal.background': t.panelBg,
    'button.background': t.tabBorder,
    'statusBar.noFolderBackground': t.statusBarBg,
    'statusBar.debuggingBackground': t.statusBarBg,
  })
  const tokenColors = (Object.keys(TOKEN_KEYS) as TokenKey[]).map((k) => ({
    name: TOKEN_KEYS[k].label,
    scope: TOKEN_SCOPES[k],
    settings: {
      foreground: t[k],
      ...(k === 'comment' && t.italicComments ? { fontStyle: 'italic' } : {}),
    },
  }))
  return {
    $schema: 'vscode://schemas/color-theme',
    name,
    type: isLight(t.editorBg) ? 'light' : 'dark',
    colors,
    tokenColors,
  }
}

const petFile = (name: PetName) => `pet-${slugify(name)}.png`

/** Markup for one pet in the webview. Animated pets are a film strip image in media/ ({{media}} is filled in at runtime). */
function petHtml(name: PetName, scale: number) {
  if (!petInfo(name).anim) return petSvg(name, scale)
  const { n, width, height, animation } = petStripLayout(name, scale)
  return `<div class="frames" style="width:${width}px;height:${height}px"><img src="{{media}}/${petFile(name)}" style="width:${width * n}px;height:${height}px;animation:frames ${animation}"></div>`
}

function extensionJs(decor: Decor, base: string, label: string, hasScene: boolean, viewId: string | null) {
  const pets = decor.pets.map((p) => petHtml(p, decor.petScale))
  const config = {
    label, pets, anim: decor.petAnim, position: decor.petPosition, base, hasScene, viewId,
    behindCode: hasScene && decor.behindCode, strength: decor.strength / 100,
  }
  return `// Generated by Theme Mockup Studio: the Pixel Pets view, and the scene behind the code.
const vscode = require('vscode')
const CONFIG = ${JSON.stringify(config)}

// A color theme can't draw an image behind the code, so that part is done by the Background extension.
// While this theme is the active one, its editor image is kept pointing at this theme's scene
// (or cleared, if this theme has none), so the image follows the theme.
const BACKGROUND_EXT = 'shalldie.background'
const isOurScene = (p) => p.includes('theme-mockup-studio.') && p.endsWith('scene.png')

async function syncBackground(context) {
  if (vscode.workspace.getConfiguration('workbench').get('colorTheme') !== CONFIG.label) return
  if (!vscode.extensions.getExtension(BACKGROUND_EXT)) {
    if (!CONFIG.behindCode || context.globalState.get('askedBackground')) return
    await context.globalState.update('askedBackground', true)
    const pick = await vscode.window.showInformationMessage(
      CONFIG.label + ': install the Background extension to show the scene behind your code.', 'Show extension')
    if (pick) vscode.commands.executeCommand('extension.open', BACKGROUND_EXT)
    return
  }
  const cfg = vscode.workspace.getConfiguration('background')
  const cur = cfg.get('editor') || {}
  const images = cur.images || []
  let next = null
  if (CONFIG.behindCode) {
    next = {
      useFront: false,
      style: { 'background-position': 'center', 'background-size': 'cover', 'image-rendering': 'pixelated', 'mix-blend-mode': 'normal', opacity: CONFIG.strength },
      styles: [],
      images: [vscode.Uri.joinPath(context.extensionUri, 'media', 'scene.png').fsPath],
      interval: 0,
      random: false,
    }
  } else if (images.length && images.every(isOurScene)) {
    next = { ...cur, images: [] }
  }
  if (next && JSON.stringify(next) !== JSON.stringify(cur)) await cfg.update('editor', next, vscode.ConfigurationTarget.Global)
}

function html(webview, sceneUri, mediaUri) {
  const csp = "default-src 'none'; img-src " + webview.cspSource + "; style-src 'unsafe-inline';"
  const top = CONFIG.position === 'perched'
  const side = CONFIG.position === 'bottom-left' ? 'left:12px;' : 'right:12px;'
  const rowPos = (top ? 'top:12px;' : 'bottom:12px;') + (CONFIG.anim === 'walk' ? '' : side)
  const pets = CONFIG.pets.map((svg, i) => '<div class="pet" style="animation-delay:' + i * 0.18 + 's">' + svg.split('{{media}}').join(mediaUri) + '</div>').join('')
  return '<!DOCTYPE html><html><head><meta charset="UTF-8"><meta http-equiv="Content-Security-Policy" content="' + csp + '">' +
    '<style>' +
    'html,body{margin:0;padding:0;height:100%;overflow:hidden;background:' + CONFIG.base + ';}' +
    '.scene{position:fixed;inset:0;image-rendering:pixelated;background-size:cover;background-position:center;opacity:' + CONFIG.strength + ';' +
    (sceneUri ? 'background-image:url(' + sceneUri + ');' : '') + '}' +
    '.row{position:fixed;display:flex;gap:6px;align-items:flex-end;' + rowPos + '}' +
    '.pet svg{display:block;filter:drop-shadow(0 2px 0 #0004)}' +
    '.frames{overflow:hidden;filter:drop-shadow(0 2px 0 #0004)}.frames img{display:block;max-width:none;image-rendering:pixelated}' +
    '@keyframes frames{to{transform:translateX(-100%)}}' +
    '.anim-bob .pet{animation:bob 1s steps(2) infinite}' +
    '.anim-hop .pet{animation:hop 1.4s ease-in-out infinite}' +
    '.anim-walk{animation:walk 14s linear infinite}.anim-walk .pet{animation:bob .5s steps(2) infinite}' +
    '@keyframes bob{0%,100%{transform:translateY(0)}50%{transform:translateY(-3px)}}' +
    '@keyframes hop{0%,60%,100%{transform:translateY(0) scaleY(1)}10%{transform:scaleY(.85)}30%{transform:translateY(-14px) scaleY(1.05)}}' +
    '@keyframes walk{0%{left:12px;transform:scaleX(-1)}49%{left:calc(100% - 12px);transform:translateX(-100%) scaleX(-1)}50%{left:calc(100% - 12px);transform:translateX(-100%) scaleX(1)}100%{left:12px;transform:scaleX(1)}}' +
    '</style></head><body><div class="scene"></div><div class="row anim-' + CONFIG.anim + '">' + pets + '</div></body></html>'
}

function activate(context) {
  syncBackground(context)
  context.subscriptions.push(
    vscode.workspace.onDidChangeConfiguration((e) => {
      if (e.affectsConfiguration('workbench.colorTheme')) syncBackground(context)
    }),
    vscode.extensions.onDidChange(() => syncBackground(context)),
  )
  if (!CONFIG.viewId) return
  context.subscriptions.push(
    vscode.window.registerWebviewViewProvider(CONFIG.viewId, {
      resolveWebviewView(view) {
        const media = vscode.Uri.joinPath(context.extensionUri, 'media')
        view.webview.options = { enableScripts: false, localResourceRoots: [media] }
        const sceneUri = CONFIG.hasScene ? view.webview.asWebviewUri(vscode.Uri.joinPath(media, 'scene.png')).toString() : ''
        view.webview.html = html(view.webview, sceneUri, view.webview.asWebviewUri(media).toString())
      },
    }),
  )
}

function deactivate() {}

module.exports = { activate, deactivate }
`
}

export async function buildVSCodePackage(t: VSCodeTheme, decor: Decor): Promise<PackageResult> {
  const themeName = t.name || 'My Theme'
  const slug = slugify(themeName)
  const id = `${slug}-theme`
  const version = `1.0.${Math.max(0, Math.floor(Date.now() / 1000) - 1_790_000_000)}`
  const hasScene = decor.scene !== 'none'
  const withView = hasScene || decor.pets.length > 0
  const label = themeName
  const themePath = `themes/${slug}-color-theme.json`
  // Each theme gets its own Pixel Pets view, shown only while that theme is active. Sharing one id made
  // every installed theme show the pets of whichever was installed first.
  const viewId = withView ? `tmsPixelPets.${slug}` : null
  const whenActive = `config.workbench.colorTheme == '${label.replace(/['\\]/g, '\\$&')}'`

  const pkg: Record<string, unknown> = {
    name: id,
    displayName: `${themeName} (Theme Mockup Studio)`,
    description: `Custom color theme${withView ? ' with a Pixel Pets view' : ''} made in Theme Mockup Studio.`,
    version,
    publisher: PUBLISHER,
    engines: { vscode: '^1.80.0' },
    categories: ['Themes'],
    contributes: {
      themes: [{ label, uiTheme: isLight(t.editorBg) ? 'vs' : 'vs-dark', path: `./${themePath}` }],
      ...(viewId ? { views: { explorer: [{ type: 'webview', id: viewId, name: 'Pixel Pets', when: whenActive }] } } : {}),
    },
    // Always present: it also keeps the behind-the-code image in step with the theme (see extensionJs).
    main: './extension.js',
    activationEvents: ['onStartupFinished', ...(viewId ? [`onView:${viewId}`] : [])],
  }

  const readme = `# ${themeName}

Made with Theme Mockup Studio.

## Install
\`\`\`
code --install-extension ${id}.vsix
\`\`\`
or Extensions view → \`···\` → **Install from VSIX…**

Then: **Ctrl+K Ctrl+T** → pick **${label}**.
${withView ? '\nYour pixel pets live in the **Explorer → Pixel Pets** panel (drag it anywhere you like).\n' : ''}${hasScene && decor.behindCode ? '\nTo see the scene behind your code, install the **Background** extension (`shalldie.background`). This theme points it at the right image whenever the theme is active; click **Apply and Reload** when Background asks.\n' : ''}
Font settings aren't part of a color theme — add these to your settings.json if you want them:
\`\`\`json
{
  "editor.fontFamily": "'${t.fontFamily}', Consolas, monospace",
  "editor.fontSize": ${t.fontSize},
  "editor.fontLigatures": ${t.ligatures}
}
\`\`\`
`

  const files: Files = {
    '[Content_Types].xml': `<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension=".json" ContentType="application/json"/>
  <Default Extension=".vsixmanifest" ContentType="text/xml"/>
  <Default Extension=".md" ContentType="text/markdown"/>
  <Default Extension=".js" ContentType="application/javascript"/>
  <Default Extension=".png" ContentType="image/png"/>
</Types>
`,
    'extension.vsixmanifest': `<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011" xmlns:d="http://schemas.microsoft.com/developer/vsx-schema-design/2011">
  <Metadata>
    <Identity Language="en-US" Id="${id}" Version="${version}" Publisher="${PUBLISHER}" />
    <DisplayName>${xmlEscape(String(pkg.displayName))}</DisplayName>
    <Description xml:space="preserve">${xmlEscape(String(pkg.description))}</Description>
    <Tags>theme,color-theme</Tags>
    <Categories>Themes</Categories>
    <GalleryFlags>Public</GalleryFlags>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="^1.80.0" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionDependencies" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionPack" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionKind" Value="ui,workspace" />
    </Properties>
  </Metadata>
  <Installation>
    <InstallationTarget Id="Microsoft.VisualStudio.Code"/>
  </Installation>
  <Dependencies/>
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.Details" Path="extension/README.md" Addressable="true" />
  </Assets>
</PackageManifest>
`,
    'extension/package.json': JSON.stringify(pkg, null, 2),
    'extension/README.md': readme,
    [`extension/${themePath}`]: JSON.stringify(vscodeColorTheme(t, label), null, 2),
  }
  files['extension/extension.js'] = extensionJs(decor, t.editorBg, label, hasScene, viewId)
  if (hasScene) {
    const png = await renderDecorPng(decor, t.editorBg, { width: 960, height: 540, bakePets: false })
    if (png) files['extension/media/scene.png'] = png
  }

  for (const p of decor.pets) if (petInfo(p).anim) files[`extension/media/${petFile(p)}`] = await petStripPng(p)

  return {
    filename: `${id}.vsix`,
    blob: zip(files, 'application/vsix'),
    note: `Install: code --install-extension ${id}.vsix  (or Extensions → ··· → Install from VSIX), then Ctrl+K Ctrl+T → "${label}".`,
  }
}
